"""Results table for the ablation harness: resume keys, row I/O, markdown.

Kept torch-free so the resume/skip logic is unit-testable without a GPU.
"""

import csv
import os
from pathlib import Path

CSV_FIELDS = [
    "timestamp",
    "backbone",
    "head",
    "mode",
    "seed",
    "epochs",
    "img_size",
    "n_test_queries",
    "mrr",
    "top1",
    "top5",
    "mAP",
    "tar@1%",
    "tar@0.1%",
    "params_total_M",
    "params_trainable_M",
    "cpu_ms",
    "onnx_ok",
    "tag",
    # Added after the first 8 rows were recorded; older rows read back empty.
    "status",
    "ort_cpu_ms",
    "error",
]

STATUS_OK = "ok"
STATUS_FAILED = "failed"

MISSING = "–"


def load_rows(csv_path) -> list[dict]:
    """All recorded rows, oldest first. Missing file = no rows."""
    path = Path(csv_path)
    if not path.exists():
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def row_status(row: dict) -> str:
    """Rows written before the status column existed are completed runs."""
    return (row.get("status") or STATUS_OK).strip() or STATUS_OK


def find_recorded(
    rows: list[dict],
    *,
    backbone: str,
    head: str,
    mode: str,
    seed,
    img_size=None,
    epochs=None,
) -> dict | None:
    """Most recent row for this cell, or None.

    img_size/epochs narrow the match only when they were overridden on the CLI;
    otherwise a cell is identified by (backbone, head, mode, seed).
    """
    want = {"backbone": backbone, "head": head, "mode": mode, "seed": str(seed)}
    if img_size is not None:
        want["img_size"] = str(img_size)
    if epochs is not None:
        want["epochs"] = str(epochs)
    for row in reversed(rows):
        if all(str(row.get(k) or "") == v for k, v in want.items()):
            return row
    return None


def failure_row(cell: dict, exc: BaseException) -> dict:
    """A failed cell is recorded, not dropped, so a resume does not retry it forever."""
    message = " ".join(str(exc).split())[:300]
    return {
        **cell,
        "status": STATUS_FAILED,
        "error": f"{type(exc).__name__}: {message}" if message else type(exc).__name__,
    }


def append_row(csv_path, row: dict) -> None:
    """Append one row, migrating the header first if new columns appeared."""
    path = Path(csv_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    _migrate_header(path)
    is_new = not path.exists()
    with open(path, "a", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_FIELDS, extrasaction="ignore")
        if is_new:
            writer.writeheader()
        writer.writerow({field: row.get(field, "") for field in CSV_FIELDS})


def _migrate_header(path: Path) -> None:
    """Rewrite in place when CSV_FIELDS grew; every existing row is carried over."""
    if not path.exists():
        return
    with open(path, newline="") as f:
        reader = csv.DictReader(f)
        header = reader.fieldnames or []
        if header == CSV_FIELDS:
            return
        rows = list(reader)
    added = [field for field in CSV_FIELDS if field not in header]
    dropped = [field for field in header if field not in CSV_FIELDS]
    if dropped:
        raise ValueError(
            f"{path.name} has columns CSV_FIELDS no longer knows: {dropped}"
        )
    print(f"[results] migrating {path.name}: adding columns {added}")
    tmp = path.with_suffix(path.suffix + ".tmp")
    with open(tmp, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_FIELDS, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row.get(field) or "" for field in CSV_FIELDS})
    os.replace(tmp, path)


def render_markdown(rows: list[dict]) -> str:
    """Completed runs as a ranked table; failed cells listed below so they are
    distinguishable from cells nobody has run yet."""
    done = [r for r in rows if row_status(r) == STATUS_OK]
    failed = [r for r in rows if row_status(r) == STATUS_FAILED]
    # Sort: finetune before probe, then by MRR descending.
    done.sort(key=lambda row: (row["mode"] != "finetune", -_number(row.get("mrr"))))

    lines = [
        "# Ablation results",
        "",
        "_Auto-generated by `scripts/run_ablation.py`. Do not edit by hand._",
        "",
        "| backbone | head | mode | seed | MRR | Top-1 | Top-5 | mAP | TAR@1% | "
        "params(M) | torch ms | ORT ms | ONNX | tag |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for row in done:
        lines.append(
            "| {backbone} | {head} | {mode} | {seed} | {mrr} | {top1} | {top5} "
            "| {mAP} | {tar1} | {params} | {cpu} | {ort} | {onnx} | {tag} |".format(
                backbone=row.get("backbone"),
                head=row.get("head"),
                mode=row.get("mode"),
                seed=row.get("seed"),
                mrr=_fmt(row.get("mrr")),
                top1=_fmt(row.get("top1")),
                top5=_fmt(row.get("top5")),
                mAP=_fmt(row.get("mAP")),
                tar1=_fmt(row.get("tar@1%")),
                params=_cell(row.get("params_total_M")),
                cpu=_cell(row.get("cpu_ms")),
                ort=_cell(row.get("ort_cpu_ms")),
                onnx=_fmt_onnx(row.get("onnx_ok")),
                tag=_cell(row.get("tag"), empty=""),
            )
        )

    if failed:
        lines += [
            "",
            "## Failed cells",
            "",
            "Recorded so a resume skips them; re-run with `--force`.",
            "",
            "| backbone | head | mode | seed | when | error |",
            "|---|---|---|---|---|---|",
        ]
        for row in failed:
            lines.append(
                "| {backbone} | {head} | {mode} | {seed} | {when} | {error} |".format(
                    backbone=row.get("backbone"),
                    head=row.get("head"),
                    mode=row.get("mode"),
                    seed=row.get("seed"),
                    when=_cell(row.get("timestamp")),
                    error=_cell(row.get("error")).replace("|", "\\|"),
                )
            )

    return "\n".join(lines) + "\n"


def write_markdown(md_path, rows: list[dict]) -> None:
    Path(md_path).write_text(render_markdown(rows))


def _number(value) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def _cell(value, empty=MISSING) -> str:
    """Old rows read back empty for columns added later."""
    return empty if value in (None, "") else str(value)


def _fmt(value) -> str:
    try:
        return f"{float(value):.3f}"
    except (TypeError, ValueError):
        return _cell(value)


def _fmt_onnx(value) -> str:
    """Render the CSV's onnx_ok cell; "skipped" must not read as a failure."""
    if value == "True":
        return "✅"
    if value in (None, "", "skipped"):
        return MISSING
    return "❌"
